import pandas as pd


def prepare_export_structure(df: pd.DataFrame) -> pd.DataFrame:
    """Формирует итоговую структуру колонок согласно заданному порядку."""

    # 1. Переименовываем только Физ и Псих.
    # 'Тех' намеренно НЕ переименовываем, чтобы столбец 'Технические' остался пустым для твоих расчетов.
    df = df.rename(columns={
        'Сумма транфера': 'Сумма трансфера',
        'Физ': 'Физические',
        'Псих': 'Психологические'
    })

    # 2. Список целевых колонок
    target_columns = [
        'Возраст',
        'Позиции',
        'Имя',
        'Зарплата',
        'Сумма трансфера',
        'Ликвидность',
        'Характер',
        'Физические',
        'Психологические',
        'Технические',  # Будет создан пустым, так как мы не переименовали в него 'Тех'
        'ОВР',
        'Вратарь',
        # Роли вратарей
        'Вратарь (Зщ)',
        'Вратарь-чистильщик (Зщ)',
        'Вратарь-чистильщик (По)',
        'Вратарь-чистильщик (Ат)',
        # Остальные позиции
        'ЦЗ',
        'КЗ',
        'ОП',
        'ЦП',
        'КП',
        'АП',
        'АКП',
        'ЦН'
    ]

    # 3. Гарантируем наличие всех требуемых колонок (если нет — создаем пустые)
    for col in target_columns:
        if col not in df.columns:
            df[col] = None

    # Возвращаем DataFrame с точным порядком колонок
    return df[target_columns]


def save_to_csv(df: pd.DataFrame, output_path: str) -> None:
    """Сохраняет итоговый DataFrame в CSV файл с разделителем ';', чтобы Excel правильно разбивал колонки."""
    formatted_df = prepare_export_structure(df)
    formatted_df.to_csv(output_path, sep=';', index=False, encoding='utf-8-sig')
